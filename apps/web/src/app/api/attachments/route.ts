import { z } from 'zod';
import { AttachmentKind, MAX_UPLOAD_BYTES } from '@evenbooks/contracts';
import { listAttachmentsFor, uploadAttachment, ServiceError } from '@evenbooks/services';
import { errorResponse, inCompany, route } from '@/server/api';
import { getStorage } from '@/server/storage';

const Query = z.object({ entityType: z.string(), entityId: z.uuid() });

export const GET = route({ query: Query }, async ({ principal, query }) => inCompany(principal, (s) => listAttachmentsFor(s, query.entityType, query.entityId)));

/** multipart/form-data: file, kind, [entityType, entityId] */
export const POST = route({}, async ({ principal, req, requestId }) => {
  const form = await req.formData().catch(() => null);
  if (!form) return errorResponse('validation', 'Expected multipart form data', 400, undefined, requestId);
  const file = form.get('file');
  if (!(file instanceof File)) return errorResponse('validation', 'Choose a file to upload.', 400, undefined, requestId);
  if (file.size > MAX_UPLOAD_BYTES) return errorResponse('validation', `That file is larger than ${MAX_UPLOAD_BYTES / 1024 / 1024} MB. Use a smaller file.`, 400, undefined, requestId);
  const kind = AttachmentKind.parse(form.get('kind') ?? 'receipt');
  if (kind === 'invoice_pdf') throw new ServiceError('validation', 'Invoice PDFs are generated by the system');
  const entityType = (form.get('entityType') as string | null) || null;
  const entityId = (form.get('entityId') as string | null) || null;
  if (entityId && !z.uuid().safeParse(entityId).success) return errorResponse('validation', 'That record could not be found.', 400, undefined, requestId);
  const body = new Uint8Array(await file.arrayBuffer());
  return inCompany(principal, (s) => uploadAttachment(s, getStorage(), { kind, fileName: file.name || 'upload', contentType: file.type || 'application/octet-stream', body, entityType, entityId }));
});
