import { pgTable, text, uuid, integer, boolean, date, numeric, jsonb, bigserial } from 'drizzle-orm/pg-core';
import { sql } from 'drizzle-orm';
import { timestamptz } from './columns';

/** Online payments through a payment processor (docs/payments-plan.md). */

export const PROCESSOR_PROVIDERS = ['stripe'] as const;
export type ProcessorProvider = (typeof PROCESSOR_PROVIDERS)[number];

export const paymentProcessorConnections = pgTable('payment_processor_connections', {
  id: uuid().primaryKey().defaultRandom(),
  companyId: uuid().notNull(),
  provider: text({ enum: PROCESSOR_PROVIDERS }).notNull(),
  providerAccountId: text().notNull(),
  status: text({ enum: ['pending', 'active', 'restricted', 'disconnected'] }).notNull().default('pending'),
  chargesEnabled: boolean().notNull().default(false),
  payoutsEnabled: boolean().notNull().default(false),
  detailsSubmitted: boolean().notNull().default(false),
  displayName: text(),
  /** created: Evenbooks created the account (hosted onboarding); linked: an existing account connected through OAuth. */
  origin: text({ enum: ['created', 'linked'] }).notNull().default('created'),
  /** Stripe balance (available + pending) the account already held when linked. */
  linkedBalance: numeric({ precision: 20, scale: 6 }),
  linkedAt: timestamptz(),
  clearingAccountId: uuid().notNull(),
  feeAccountId: uuid().notNull(),
  payoutBankAccountId: uuid(),
  allowCard: boolean().notNull().default(true),
  allowAch: boolean().notNull().default(true),
  allowPartial: boolean().notNull().default(true),
  minimumPayment: numeric({ precision: 20, scale: 6 }).notNull().default('1'),
  autoPostPayouts: boolean().notNull().default(true),
  lastEventAt: timestamptz(),
  lastError: text(),
  lastErrorAt: timestamptz(),
  disconnectedAt: timestamptz(),
  createdBy: text().notNull(),
  version: integer().notNull().default(1),
  createdAt: timestamptz().notNull().default(sql`now()`),
  updatedAt: timestamptz().notNull().default(sql`now()`),
});

export const processorEvents = pgTable('processor_events', {
  id: bigserial({ mode: 'number' }).primaryKey(),
  provider: text().notNull(),
  providerEventId: text().notNull(),
  providerAccountId: text(),
  eventType: text().notNull(),
  payload: jsonb().$type<Record<string, unknown>>().notNull(),
  occurredAt: timestamptz(),
  receivedAt: timestamptz().notNull().default(sql`now()`),
  companyId: uuid(),
  connectionId: uuid(),
  processedAt: timestamptz(),
  attempts: integer().notNull().default(0),
  lastError: text(),
});

export const processorCharges = pgTable('processor_charges', {
  id: uuid().primaryKey().defaultRandom(),
  companyId: uuid().notNull(),
  connectionId: uuid().notNull(),
  provider: text().notNull(),
  providerPaymentIntentId: text(),
  providerCheckoutSessionId: text(),
  providerChargeId: text(),
  providerBalanceTransactionId: text(),
  invoiceId: uuid(),
  contactId: uuid(),
  origin: text({ enum: ['evenbooks', 'external'] }).notNull(),
  method: text({ enum: ['card', 'ach', 'unknown'] }).notNull().default('unknown'),
  status: text({ enum: ['pending', 'processing', 'succeeded', 'failed', 'canceled'] }).notNull().default('pending'),
  currency: text().notNull(),
  amount: numeric({ precision: 20, scale: 6 }).notNull(),
  processorFee: numeric({ precision: 20, scale: 6 }).notNull().default('0'),
  platformFee: numeric({ precision: 20, scale: 6 }).notNull().default('0'),
  platformFeeRefunded: numeric({ precision: 20, scale: 6 }).notNull().default('0'),
  amountRefunded: numeric({ precision: 20, scale: 6 }).notNull().default('0'),
  amountDisputed: numeric({ precision: 20, scale: 6 }).notNull().default('0'),
  paymentId: uuid(),
  feeJournalEntryId: uuid(),
  payerEmail: text(),
  description: text(),
  failureMessage: text(),
  succeededAt: timestamptz(),
  expiresAt: timestamptz(),
  createdBy: text().notNull(),
  version: integer().notNull().default(1),
  createdAt: timestamptz().notNull().default(sql`now()`),
  updatedAt: timestamptz().notNull().default(sql`now()`),
});

export const processorRefunds = pgTable('processor_refunds', {
  id: uuid().primaryKey().defaultRandom(),
  companyId: uuid().notNull(),
  chargeId: uuid().notNull(),
  provider: text().notNull(),
  providerRefundId: text(),
  providerDisputeId: text(),
  kind: text({ enum: ['refund', 'dispute', 'dispute_reversal'] }).notNull(),
  origin: text({ enum: ['evenbooks', 'external'] }).notNull(),
  status: text({ enum: ['pending', 'succeeded', 'failed', 'canceled'] }).notNull().default('pending'),
  amount: numeric({ precision: 20, scale: 6 }).notNull(),
  feeAmount: numeric({ precision: 20, scale: 6 }).notNull().default('0'),
  platformFeeRefunded: numeric({ precision: 20, scale: 6 }).notNull().default('0'),
  reason: text(),
  disputeStatus: text(),
  refundId: uuid(),
  paymentId: uuid(),
  feeJournalEntryId: uuid(),
  failureMessage: text(),
  requestedBy: text().notNull(),
  version: integer().notNull().default(1),
  createdAt: timestamptz().notNull().default(sql`now()`),
  updatedAt: timestamptz().notNull().default(sql`now()`),
});

export const processorPayouts = pgTable('processor_payouts', {
  id: uuid().primaryKey().defaultRandom(),
  companyId: uuid().notNull(),
  connectionId: uuid().notNull(),
  provider: text().notNull(),
  providerPayoutId: text().notNull(),
  status: text({ enum: ['pending', 'in_transit', 'paid', 'failed', 'canceled'] }).notNull(),
  currency: text().notNull(),
  amount: numeric({ precision: 20, scale: 6 }).notNull(),
  arrivalDate: date({ mode: 'string' }).notNull(),
  description: text(),
  bankAccountId: uuid(),
  journalEntryId: uuid(),
  reversalEntryId: uuid(),
  failureMessage: text(),
  version: integer().notNull().default(1),
  createdAt: timestamptz().notNull().default(sql`now()`),
  updatedAt: timestamptz().notNull().default(sql`now()`),
});
